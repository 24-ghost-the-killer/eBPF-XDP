// ISO-3166 alpha-2 -> flag emoji (two regional-indicator letters).
export const flagOf = (cc?: string) => (cc && /^[A-Za-z]{2}$/.test(cc) ? String.fromCodePoint(...[...cc.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65)) : '🏳️')

// Great-circle distance in km between two points (for "a 7,300 km link").
export function distanceKm(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const r = Math.PI / 180
  const h = Math.sin(((b.lat - a.lat) * r) / 2) ** 2 + Math.cos(a.lat * r) * Math.cos(b.lat * r) * Math.sin(((b.lng - a.lng) * r) / 2) ** 2
  return 2 * 6371 * Math.asin(Math.min(1, Math.sqrt(h)))
}

export function countryCentroid(cc?: string | null): { lat: number; lng: number } | null {
  const p = cc ? C[cc.toUpperCase()] : undefined
  return p ? { lat: p[0], lng: p[1] } : null
}
